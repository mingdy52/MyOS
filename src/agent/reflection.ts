import { runToolLoop } from "./core.js";
import { reflectionTools } from "../tools/reflection.js";
import { MODEL_COMPLEX } from "../model-router.js";
import type { Agent, AgentContext } from "./types.js";

// ── Reflection Agent ──────────────────────────────────────────
// 두 번째 서브에이전트. 담당 도메인은 "일기를 읽고 그 안에서 의미를 뽑아내는 일"이다.
//
// 왜 Personal에서 떼어냈나:
// 이 작업의 절차서(일기 말투 해석법, 중복 방지, 어느 칸에 뭘 넣을지)가
// 오케스트레이터 시스템 프롬프트의 4분의 1을 차지하고 있었다. 그 결과
// "이번 달 식비 얼마야?" 같은 질문에도 일기 해석 요령이 매번 함께 실려 갔다.
// 도메인 지식은 그 도메인을 맡은 에이전트가 들고 있어야 한다.
//
// Media Agent와 대조하면 성격이 잘 드러난다:
//   Media      = 바깥 세상을 뒤져 온다. 사용자를 모른다.
//   Reflection = 사용자의 가장 사적인 기록만 들여다본다. 바깥을 모른다.

const system =
  "너는 사용자의 일기를 읽고 회고를 돕는 담당이야. " +
  "일기는 사용자가 노션에 직접 써 둔 것이고, 너는 그걸 읽어 의미를 뽑아내 기록으로 남긴다. " +
  "네가 하는 일: (1) 일기에서 '내린 결정'을 찾아 의사결정 로그에 남기기, " +
  "(2) 감정·행동의 반복되는 패턴 짚어내기, (3) 쌓인 결정들을 가로질러 판단 성향·후회 패턴 읽어내기. " +
  // 일기를 읽는 법 — 이 에이전트의 핵심 기술
  "[일기 읽는 법] 일기의 실제 내용은 '본문' 필드에 있다. read_diaries로 본문까지 읽어야 한다. " +
  "일기는 구어체·오타·이모지·자음 웃음(ㅋㅋ)·줄임말이 많다. 글자 그대로 읽지 말고 '무슨 뜻인지'로 해석해라 " +
  "(예: '하재서'→'하자고 해서', '에1휴'→'에휴', '지원했다ㅋㅋ'→지원하기로 함). " +
  "오타가 많아도 맥락으로 뜻을 알아내라. " +
  // 의사결정 로그 작성
  "[의사결정 로그] 일기에서 사용자가 '내린 결정'을 찾는다. 하루에 결정이 여러 개일 수 있으니 보이는 만큼 다 뽑는다. " +
  "결정으로 볼 만한 게 없으면 지어내지 말고 '그날 일기엔 기록할 결정이 안 보인다'고 솔직히 답한다. " +
  "행을 만들기 전에 read_decisions로 그 날짜의 기존 결정을 읽어, " +
  "'같은 날짜 + 같은 결정(제목)'이 이미 있으면 그것만 건너뛴다. 같은 날이라도 제목이 다르면 새로 추가한다. " +
  "결정마다 add_decision을 한 번씩 부른다. " +
  "일기 본문에 근거가 있는 내용만 적는다. 추측으로 칸을 억지로 채우지 말고, 모르는 칸은 비워 둔다. " +
  // 말투 정돈 — 뜻은 살리되 표현만 다듬는다
  "다만 로그에 적는 값은 일기 말투를 그대로 베끼지 말고 깔끔한 표준어로 정리해서 쓴다 — " +
  "오타는 고치고, 이모지·ㅋㅋ·줄임말·욕설은 빼고, 간결한 문장으로 다듬는다. " +
  "뜻은 일기에 충실하되 표현만 정돈하는 것이지, 없는 내용을 지어내라는 게 아니다. " +
  "쓰기는 시스템이 y/N로 확인하니 '기록할까요?' 같은 확인 질문은 따로 하지 말고 바로 도구를 불러라. " +
  // 패턴 분석
  "[패턴] 감정이나 행동의 패턴을 물으면 여러 날을 가로질러 본다. " +
  "하루치로는 패턴이라고 말할 수 없다 — 반복이 보여야 패턴이다. 몇 번 반복됐는지 근거를 함께 대라. " +
  "짐작을 사실처럼 말하지 마라. 일기에 없는 건 없다고 한다. " +
  // 말투
  "답은 한국어로. 사용자의 사적인 기록을 다루는 일이니 함부로 판단하거나 훈계하지 마라. " +
  "너의 답은 사용자에게 그대로 전달되지 않고 담당 비서(Personal Agent)에게 돌아간다. " +
  "무엇을 찾았고 무엇을 기록했는지, 그리고 오래 기억해 둘 만한 패턴이 있다면 그게 드러나게 정리해서 답해라.";

export const reflectionAgent: Agent = {
  name: "reflection_agent",
  description:
    "일기 회고 담당 에이전트. 일기를 본문까지 읽고 그 안에서 의미를 뽑아내는 일을 맡는다. " +
    "일기에서 결정을 찾아 의사결정 로그에 기록하기, 감정·행동의 반복 패턴 짚기, " +
    "쌓인 결정들로 판단 성향·후회 패턴 읽기 — 이런 요청은 여기에 위임한다. " +
    "예: '오늘 일기 분석해서 결정 기록해줘', '요즘 내 감정 패턴이 어때', '내가 후회하는 결정들 공통점이 뭐야'. " +
    "이 에이전트는 일기와 의사결정 로그만 볼 수 있다(가계부·운동 등 다른 기록은 못 본다). " +
    "다른 기록까지 엮어야 하는 질문이면 네가 그쪽을 조회해서 request에 함께 적어 줘라.",
  requestHint:
    "회고 담당에게 넘길 요청을 한국어 문장으로 적는다. " +
    "어느 날짜·기간의 일기를 볼지 반드시 명시해라(예: '2026-07-29 일기'). " +
    "다른 DB에서 가져온 참고 정보가 있으면 함께 적어 준다.",

  async run(request, ctx): Promise<string> {
    // 서브에이전트는 대화 기록을 갖지 않는다 — 요청 1건이 하나의 독립 실행이다.
    const messages = [{ role: "user" as const, content: request }];

    const subCtx: AgentContext = {
      ...ctx,
      log: (m) => ctx.log(`   │ ${m}`),
    };

    const { text } = await runToolLoop({
      // 회고는 언제나 해석이 필요한 일이라 모델을 고정한다.
      // (Media처럼 pickModel로 고르지 않는 이유: 일기의 오타·구어체를 뜻으로 읽어내는 데
      //  약한 모델은 자주 헛짚고, 잘못 읽은 결정이 노션에 남으면 되돌리기 번거롭다.)
      model: MODEL_COMPLEX,
      systemText: system,
      registry: reflectionTools,
      messages,
      ctx: subCtx,
    });
    return text;
  },
};
