import { runToolLoop } from "./core.js";
import { mediaTools } from "../tools/media.js";
import { pickModel } from "../model-router.js";
import type { Agent, AgentContext } from "./types.js";

// ── Media Agent ───────────────────────────────────────────────
// 첫 번째 서브에이전트. 담당 도메인은 "기분을 돌보는 콘텐츠"다.
//
// Personal Agent(오케스트레이터)와의 차이가 이 파일의 요점이다:
//  - Personal은 "사용자가 왜 이런 상태인지"를 안다(일기·운동·소비 기록을 본다).
//  - Media는 그 이유를 모른다. "이 감정이면 이런 콘텐츠"만 잘하면 된다.
// 그래서 Media는 노션 도구 전체가 아니라 콘텐츠 도구 3개만 들고 있고,
// 맥락은 Personal이 요청 문장에 담아 넘겨준다.

const system =
  "너는 사용자의 기분을 돌보는 콘텐츠 담당이야. " +
  "영상·음악·사진·글귀를 보관함(노션 '콘텐츠' DB)에 모아두고, 감정에 맞는 걸 꺼내 추천한다. " +
  "네가 하는 일은 두 가지다: (1) 사용자가 마음에 들어 한 콘텐츠를 태그 붙여 저장하기, " +
  "(2) 감정에 맞는 콘텐츠를 보관함에서 꺼내 추천하기. " +
  "보관함은 '좋았던 것만 모아둔 곳'이다 — 저장돼 있다는 것 자체가 사용자가 좋아했다는 뜻이라 별도의 평가 표시는 없다. " +
  // 링크 환각 금지 — 이 에이전트에서 가장 중요한 규칙
  "[절대 규칙] 영상 URL을 네 머릿속에서 지어내면 안 된다. 그럴듯해 보여도 실제로는 없는 페이지다. " +
  "네가 사용자에게 건네는 링크는 반드시 list_media(보관함) 결과에서 나온 것이어야 한다. " +
  // 추천할 때
  "[추천] 추천 요청을 받으면 먼저 list_media로 보관함을 확인한다. " +
  "요청에 감정이 적혀 있으면 그 감정으로 걸러 보고, 결과가 비면 조건을 넓혀 다시 본다(감정 빼고 전체 조회 등). " +
  "보관함에 있는 건 이미 검증된 것이니 그쪽을 먼저 고른다. " +
  "보관함이 비었거나 맞는 게 없으면 솔직히 '아직 저장된 게 없다'고 말하고, " +
  "어떤 걸 저장해두면 좋을지 한 줄로 제안한다(링크를 지어내지 말고 종류만 말해라). " +
  "추천은 2~3개까지만. 각각 제목·링크와 함께 '왜 지금 이게 맞는지'를 한 문장으로 붙인다. " +
  // 저장할 때
  "[저장] 저장은 '사용자가 이걸 좋아했다'는 기록이다. 그러니 사용자가 좋다고 한 것만 저장한다. " +
  "제목·URL을 확인하고, 감정·태그는 사용자가 말하지 않았어도 네가 판단해서 채운다(나중에 감정으로 찾으려면 필요하다). " +
  "먼저 list_media로 같은 URL이 이미 있는지 보고, 있으면 중복이라고 알리고 저장하지 않는다. " +
  "반대로 저장해 둔 걸 보고 '별로였다'고 하면 delete_media로 뺀다 — 보관함에는 좋았던 것만 남긴다. " +
  // 말투
  "답은 한국어로, 짧고 담백하게. 위로랍시고 과장하거나 설교하지 마라. " +
  "너의 답은 사용자에게 그대로 전달되지 않고 담당 비서(Personal Agent)에게 돌아가니, " +
  "무엇을 왜 골랐는지가 드러나게 정리해서 답해라.";

export const mediaAgent: Agent = {
  name: "media_agent",
  description:
    "기분을 돌보는 콘텐츠(영상·음악·사진·글귀) 담당 에이전트. " +
    "위로가 될 만한 콘텐츠를 추천받거나, 마음에 든 링크를 보관함에 저장할 때 이 에이전트에 위임한다. " +
    "예: '우울할 때 볼 영상 추천해줘', '아까 그 영상 좋았어, 저장해줘'. " +
    "이 에이전트는 사용자의 일기·기록을 볼 수 없으니, 감정이나 상황은 네가 request에 적어서 알려줘야 한다.",
  requestHint:
    "콘텐츠 담당에게 넘길 요청을 한국어 문장으로 적는다. " +
    "추천이면 파악한 감정·상황·원하는 유형을 함께 적어라(예: '요즘 야근으로 지쳐 있음. 잔잔한 영상 2개 추천'). " +
    "저장이면 URL과 제목, 아는 정보를 적는다.",

  async run(request, ctx): Promise<string> {
    // 서브에이전트는 대화 기록을 갖지 않는다 — 요청 1건이 곧 하나의 독립 실행이다.
    // 맥락이 필요하면 Personal이 request에 담아 준다. (기억은 Personal 쪽 몫)
    const messages = [{ role: "user" as const, content: request }];

    // 로그를 한 단계 들여써서 "지금은 서브에이전트가 일하는 중"임을 눈으로 구분한다.
    const subCtx: AgentContext = {
      ...ctx,
      log: (m) => ctx.log(`   │ ${m}`),
    };

    const { text } = await runToolLoop({
      model: pickModel(request),
      systemText: system,
      registry: mediaTools,
      messages,
      ctx: subCtx,
    });
    return text;
  },
};
